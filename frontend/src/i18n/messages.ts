function legacyPackageId(value: string): boolean {
  return /^[1-9][0-9]{0,15}$/u.test(value) && Number.isSafeInteger(Number(value));
}

export function translateKnownMessage(value: string): string | undefined {
  if (value.length > 4096 || /[\u0000-\u001f\u007f]/u.test(value)) return undefined;
  if (Object.hasOwn(messages, value)) return messages[value];
  // Structured warnings contain arbitrary names; never include those names in feedback.
  const emptyGroupPrefix = "Empty group uses REJECT: ";
  if (value.startsWith(emptyGroupPrefix) && value.slice(emptyGroupPrefix.length).trim()) {
    return "空策略组已使用 REJECT，请检查模板中的组成员。";
  }
  const missingMappingsPrefix = "Map every in-use legacy package before importing: ";
  if (value.startsWith(missingMappingsPrefix)) {
    const identifiers = value.slice(missingMappingsPrefix.length).split(", ");
    if (identifiers.length <= 10_000 && identifiers.every(legacyPackageId)) {
      return "导入前请为所有正在使用的旧套餐指定映射。";
    }
  }
  const missingPlan = /^Legacy package ([1-9][0-9]{0,15}): selected plan no longer exists$/u.exec(value);
  if (missingPlan && legacyPackageId(missingPlan[1])) {
    return "旧套餐映射所选的目标套餐已不存在。";
  }
  const legacyTemplate = /^(.{1,120}): legacy template (.{1,255}) must be mapped manually$/u.exec(value);
  if (legacyTemplate && legacyTemplate[1].trim() && legacyTemplate[2].trim()) {
    return "旧模板需要手动指定映射。";
  }
  const legacyKeyCollision = /^(.{1,80}): a legacy subscription key collides with (.{1,80})$/u.exec(value);
  if (legacyKeyCollision && legacyKeyCollision[1].trim() && legacyKeyCollision[2].trim()) {
    return "旧订阅凭据与另一用户的凭据冲突。";
  }
  const separator = value.lastIndexOf(": ");
  if (separator > 0 && value.slice(0, separator).trim()) {
    const reason = value.slice(separator + 2);
    if (Object.hasOwn(subscriptionCompatibilityMessages, reason)) {
      return `已排除不兼容节点：${subscriptionCompatibilityMessages[reason]}`;
    }
    if (Array.from(value.slice(0, separator)).length <= 120 && Object.hasOwn(legacyImportMessages, reason)) {
      return legacyImportMessages[reason];
    }
  }
  // Only bounded, fixed validation templates may contribute parameters.
  const length = /^String should have (at least|at most) ([0-9]{1,9}) characters$/u.exec(value);
  if (length) return `字符串${length[1] === "at least" ? "至少" : "最多"}应包含 ${length[2]} 个字符。`;
  const bound = /^Input should be (greater than or equal to|less than or equal to|greater than|less than) (-?[0-9]{1,16}(?:\.[0-9]{1,8})?)$/u.exec(value);
  if (bound) {
    const labels: Record<string, string> = { "greater than or equal to": "大于或等于", "less than or equal to": "小于或等于", "greater than": "大于", "less than": "小于" };
    return `输入值应${labels[bound[1]]} ${bound[2]}。`;
  }
  if (value.startsWith("Value error, ")) {
    const reason = value.slice("Value error, ".length);
    if (Object.hasOwn(messages, reason)) return messages[reason];
  }
  return undefined;
}
